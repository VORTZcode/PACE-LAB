import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
const txt=p=>readFileSync(p,'utf8');
const engine=txt('ios/PaceLabCompanion/HealthSyncEngine.swift');
const bridge=txt('ios/PaceLabCompanion/PaceLabCompanionApp.swift');
const app=txt('assets/native-health.js');
const index=txt('index.html');
assert.match(engine,/HKObserverQuery/);
assert.match(engine,/HKAnchoredObjectQuery/);
assert.match(engine,/healthkit-workout-anchor\.bin/);
assert.match(engine,/page\.deleted/);
assert.doesNotMatch(engine,/addingTimeInterval\(-30\*24\*3600\)/);
assert.doesNotMatch(engine,/limit: 40/);
assert.match(bridge,/engine\.resync\(\)/);
assert.match(app,/liveIDs/);
assert.match(engine,/enableBackgroundDelivery/);
assert.match(engine,/local-healthkit-workouts\.json/);
assert.match(engine,/\.addingTimeInterval\(180\)/);
// Regression: HK heart-rate recovery is expressed in beats/min, never plain count.
assert.match(engine,/recordedRecovery\.first\?\.quantity\.doubleValue\(for: bpmUnit\)/);
assert.doesNotMatch(engine,/recordedRecovery\.first\?\.quantity\.doubleValue\(for: HKUnit\.count\(\)\)/);
assert.match(bridge,/HealthSyncEngine\.shared\.startObservers\(\)/);
assert.doesNotMatch(bridge,/WKWebView/);
assert.match(app,/source_uuid/);
assert.match(index,/native-health\.js/);
assert.doesNotMatch(index,/cloud-sync\.js/);
assert.ok(!existsSync('assets/cloud-sync.js'));
assert.ok(!existsSync('supabase/schema/healthkit.sql'));
for(const path of ['ios/PaceLabCompanion/WebApp/index.html','ios/PaceLabCompanion/WebApp/assets/native-health.js']) assert.ok(existsSync(path));
