import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src = name => readFileSync('ios/PaceLabCompanion/' + name,'utf8');
const plan = JSON.parse(src('AppData/pace-programme.json'));
const model = src('PaceModels.swift');
const view = src('PaceViewsProgramme.swift');
const coach = src('PaceCoachEngine.swift');
const screen = src('PaceCoachScreen.swift');
const tracker = src('PaceStrengthTracker.swift');
assert.equal(plan.force.length,18);
assert.ok(plan.force.every(x => ['seconds','repetitions'].includes(x.measurement_unit)));
const timed = plan.force.filter(x=>x.measurement_unit==='seconds');
assert.deepEqual(timed.map(x=>x.name).sort(),
  ['Planche avant','Planche latérale','Marche du fermier 1 haltère'].sort());
assert.equal(timed.find(x=>x.name==='Planche avant').load_expected,false);
assert.equal(timed.find(x=>x.name==='Planche latérale').load_expected,false);
assert.equal(timed.find(x=>x.name==='Marche du fermier 1 haltère').load_expected,true);
assert.equal(plan.force.find(x=>x.name==='Rowing 1 bras appui stable').measurement_unit,'repetitions');
assert.match(model,/var metricLabel: String \{ isTimed \? "Durée \(s\)" : "Répétitions" \}/);
assert.match(view, /@State private var expandedExerciseID: String\?/);
assert.match(view, /private var exerciseCompletionSignature: \[Bool\]/);
assert.match(view, /\.onChange\(of: exerciseCompletionSignature\)/);
assert.match(view, /advanceAfterCompletion\(from: old, to: new\)/);
assert.match(view, /let expanded = expandedExerciseID == ex\.id/);
assert.match(view, /if expanded \{/);
assert.match(view, /PaceStrengthSetRow\(dayDate: day\.date, exercise: ex,/);
assert.match(view, /title: exercise\.metricLabel/);
assert.match(view, /if exercise\.tracksLoad \{/);
assert.match(view, /Durée réalisée en secondes/);
assert.match(coach, /shareStrengthSets = UserDefaults\.standard\.bool/);
assert.match(coach, /if shareStrengthSets, let strength/);
assert.match(screen, /Toggle\(isOn:\$coach\.shareStrengthSets\)/);
assert.match(tracker, /exercise\.isTimed \? "secondes" : "répétitions"/);
assert.match(tracker, /HISTORIQUE DE MUSCULATION SAISI PAR L'UTILISATEUR/);
assert.match(tracker, /pace-strength-sets\.json/);
console.log('V3.7: 18 exercise units, 3 timed movements, load semantics, focused accordion, automatic advance and opt-in coach summary validated.');
