import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = name => readFileSync('ios/PaceLabCompanion/' + name + '.swift','utf8');
const progress = read('PaceViewsProgress');
const activities = read('PaceViewsActivities');
const evidence = read('PaceProgressEvidence');
const home = read('PaceViewsCore');
const coach = read('PaceLivingCoach');
assert.match(progress, /struct PaceTrainingTimeline: View/);
assert.match(progress, /PaceProgressEvidence\.trainingWeeks\(engine\.runHistory/);
assert.match(progress, /chartXSelection\(value: \$selectedWeekDate\)/);
assert.match(progress, /chartXSelection\(value: \$selectedMonth\)/);
assert.match(progress, /validatedRuns\(engine\.runHistory/);
assert.match(progress, /NavigationLink[\s\S]*WorkoutDetailScreen\(workout: workout\)/);
assert.match(progress, /26 semaines/);
assert.match(progress, /52 semaines/);
assert.match(activities, /\.searchable\(text: \$searchText/);
assert.match(activities, /searchText\.trimmingCharacters/);
assert.match(activities, /\.sorted \{ \$0\.1 > \$1\.1 \}/);
assert.match(evidence, /static func trainingWeeks/);
assert.match(evidence, /static func validatedRuns/);
assert.match(evidence, /let runs = validRuns\(workouts, at: now\)/);
assert.match(home, /Text\(PaceFormat\.duration\(latest\.duration_seconds\)\)/);
assert.match(home, /PaceFormat\.distance\(latest\.kilometers, places: 2\)/);
assert.match(coach, /Text\(signal\.origin\)[\s\S]*foregroundStyle\(PaceColors\.teal\)/);
console.log('PACE LAB V8: searchable history, weekly/yearly progress exploration and validated drilldowns.');
