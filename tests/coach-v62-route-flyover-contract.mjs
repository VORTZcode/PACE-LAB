import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = name => readFileSync('ios/PaceLabCompanion/'+name+'.swift','utf8');
const route = source('PaceWorkoutRoute');
const health = source('HealthSyncEngine');
const activity = source('PaceViewsActivities');
const coach = source('PaceCoachEngine');
const appProject = readFileSync('ios/PaceLabCompanion.xcodeproj/project.pbxproj','utf8');

assert.ok(health.includes('HKSeriesType.workoutRoute()'), 'route permission missing');
assert.ok(route.includes('if retry {'), 'HealthKit route access must never be prompted on ordinary activity open');
assert.ok(route.includes('HKObjectType.workoutType(), HKSeriesType.workoutRoute()'), 'Both parent workout and route are required');
assert.ok(route.includes('store.requestAuthorization(toShare: [], read: reads)'), 'Read-only HealthKit authorization');
assert.ok(!route.includes('read: [HKSeriesType.workoutRoute()]'), 'Route-only authorization caused a real-device SIGABRT');
assert.ok(route.includes('HKQuery.predicateForObject(with: uuid)'));
assert.ok(route.includes('HKQuery.predicateForObjects(from: workout)'));
assert.ok(route.includes('HKWorkoutRouteQuery(route: sample)'));
assert.ok(route.includes('locations.append(contentsOf: batch)'));
assert.ok(route.includes('CLLocationCoordinate2DIsValid'));
assert.ok(route.includes('sorted { $0.timestamp < $1.timestamp }'));
assert.ok(route.includes('MKMapView'));
assert.ok(route.includes('MKPolyline('));
assert.ok(route.includes('const') === false || route.includes('struct PaceRouteTrack'));
assert.ok(route.includes('MKMapCamera('));
assert.ok(route.includes('coordinator.cameraCenter ?? current.coordinate'));
assert.ok(route.includes('PaceFlightMotion.heading('));
assert.ok(route.includes('PaceFlightMotion.center('));
assert.ok(route.includes('every: 1.0 / 30.0'), 'Replay should refresh at 30 FPS rather than 10 FPS');
assert.ok(route.includes('track.cameraCourse(at: fraction)'));
assert.ok(route.includes('MKImageryMapConfiguration(elevationStyle: .realistic'), 'Satellite imagery with realistic relief');
assert.ok(route.includes('Slider(value: $fraction'));
assert.ok(route.includes('Pause') && route.includes('Lire'));
assert.ok(route.includes('recenterToken += 1'));
assert.ok(route.includes('PaceFlyoverSpeedControl(selection: $playbackSpeed)'));
assert.ok(route.includes('selection = value'), 'Speed choices must directly update playback state');
assert.ok(route.includes('if fraction >= 1 {') && route.includes('stage = .outro') && route.includes('case .finished:'), 'Playback completes with a 3D reveal before stopping');
assert.ok(route.includes('case .unavailable:'));
assert.ok(route.includes('Parcours GPS indisponible'));
assert.ok(activity.includes('PaceRouteSection(workout: workout)'));
assert.ok(activity.includes('Button("Parcours GPS"'));
assert.ok(appProject.includes('PaceWorkoutRoute.swift in Sources'));
assert.ok(!coach.includes('HKWorkoutRouteQuery'), 'GPS must not be sent to AI implicitly');
console.log('V6.4: HealthKit read-only GPS, enlarged map, filtered flyover camera, pause, speed, seek, recenter, privacy.');
