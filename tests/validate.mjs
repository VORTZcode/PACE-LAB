import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {createRequire} from 'node:module';
const html=readFileSync('index.html','utf8');
const js=readFileSync('assets/app.js','utf8');
const program=readFileSync('assets/programme.js','utf8');
const source=program.match(/^window\.STRIDE_SEED=(.+);$/m);
assert(source, 'Programme introuvable');
const data=JSON.parse(source[1]);
assert.equal(data.plan.length,7);
assert.equal(data.force.length,18);
assert.equal(data.recipes.length,14);
for(const key of ['runs','weights','vo2','monthly']) assert.deepEqual(data[key],[],`Historique privé dans ${key}`);
assert(html.includes('assets/programme.js') && html.includes('assets/app.js'));
assert(html.includes('assets/styles.css'));
assert(!html.includes('embedded-seed'));
assert(!html.includes('2026-10-31') && !program.includes('2026-10-31'), 'L’historique a été intégré au site');
for(const name of ['sw.js','icon.svg','manifest.webmanifest','.nojekyll'])assert(existsSync(name));
assert(js.includes('PACE-LAB-PERSONAL-DATA'),'Import privé manquant');
assert(!js.includes('96 courses'),'L’historique personnel ne doit pas être codé en dur');
assert(!js.includes('105.4'),'Mesures personnelles interdites dans le dépôt');
const manifest=JSON.parse(readFileSync('manifest.webmanifest','utf8'));
assert.equal(manifest.display,'standalone');
console.log('Tests PACE LAB réussis : programme, ressources PWA, confidentialité');
