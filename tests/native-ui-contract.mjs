import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
const read = path => readFileSync(path, 'utf8');
const app = read('ios/PaceLabCompanion/PaceLabCompanionApp.swift');
const models = read('ios/PaceLabCompanion/PaceModels.swift');
const core = read('ios/PaceLabCompanion/PaceViewsCore.swift');
const activities = read('ios/PaceLabCompanion/PaceViewsActivities.swift');
const progress = read('ios/PaceLabCompanion/PaceViewsProgress.swift');
const nutrition = read('ios/PaceLabCompanion/PaceViewsNutrition.swift');
const plan = read('ios/PaceLabCompanion/PaceViewsProgramme.swift');
const body = read('ios/PaceLabCompanion/PaceViewsBody.swift');
const content = JSON.parse(read('ios/PaceLabCompanion/AppData/pace-programme.json'));
assert.deepEqual(Object.keys(content).sort(), ['force','plan','recipes']);
assert.equal(content.plan.length,7);
assert.equal(content.force.length,18);
assert.equal(content.recipes.length,14);
assert.ok(content.plan.every(x=>x.date && x.title && x.instructions));
assert.ok(content.recipes.every(x=>x.ingredients && x.method));
assert.match(app,/TabView/);
assert.doesNotMatch(app,/WKWebView/);
for (const name of ['TodayScreen','ActivitiesScreen','ProgrammeScreen','ProgressScreen','NutritionScreen']) assert.match(app,new RegExp(name));
assert.match(core,/glassEffect/);
assert.match(core,/PaceColors\.base/);
assert.match(activities,/RunDynamicsSection/);
assert.match(activities,/RunIntervalsSection/);
const dynamics = read('ios/PaceLabCompanion/PaceRunAnalysis.swift');
const intervals = read('ios/PaceLabCompanion/PaceRunIntervals.swift');
const healthEngine = read('ios/PaceLabCompanion/HealthSyncEngine.swift');
const payload = read('ios/PaceLabCompanion/LocalHealthStore.swift');
assert.match(dynamics,/chartXSelection/);
assert.match(dynamics,/Comparable|SimilarRunComparison/);
assert.match(dynamics,/cadence_estimated_spm/);
assert.match(intervals,/Découpage temporel calculé par PACE LAB/);
assert.match(healthEngine,/requestAdvancedPermission/);
for (const metric of ['runningSpeed','runningPower','runningStrideLength','runningGroundContactTime','runningVerticalOscillation']) {
  assert.match(healthEngine,new RegExp(metric));
}
assert.match(payload,/advanced_loaded: Bool\? = nil/);
assert.match(payload,/speed_series: \[PaceSensorPoint\]\? = nil/);
assert.doesNotMatch(healthEngine,/HKUnit\.count\(\)\s*\)/);
assert.match(progress,/Chart\(monthSeries\)/);
assert.match(plan,/toggleDay/);
assert.match(nutrition,/toggleMeal/);
assert.match(body,/saveBody/);
assert.match(models,/healthcompanion|class PaceLibrary|PaceBodyLog/);
assert.ok(existsSync('ios/PaceLabCompanion/Assets.xcassets/AppIcon.appiconset/AppIcon.png'));
const journal = read('ios/PaceLabCompanion/PaceSessionJournal.swift');
const groceries = read('ios/PaceLabCompanion/PaceGrocery.swift');
assert.match(journal,/FileProtectionType\.completeUntilFirstUserAuthentication/);
assert.match(journal,/effort: Int\?/);
assert.match(activities,/PaceEffortEditor/);
assert.match(activities,/date <= workout\.endDate/);
assert.match(groceries,/ShareLink\(item: sharedText\)/);
assert.match(groceries,/toggleGrocery/);
assert.match(nutrition,/GroceryScreen/);
assert.match(models,/shoppingChecked/);
console.log('V2.2 native: graphiques interactifs, comparaisons descriptives, données HealthKit optionnelles et fonctions précédentes validés.');
